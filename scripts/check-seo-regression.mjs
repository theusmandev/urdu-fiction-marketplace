/**
 * UNB Premium — Automated SEO Regression Suite (check:seo)
 *
 * Verifies key SEO invariants across generated HTML build artifacts,
 * route metadata definitions, sitemap, robots.txt, and content security:
 * 1. Exactly 1 <link rel="canonical"> with absolute URL without query strings.
 * 2. Exactly 1 <h1> heading per public content page.
 * 3. Title length (<= 80 chars) and meta description (<= 180 chars).
 * 4. Robots.txt and edge proxy/middleware X-Robots-Tag noindex enforcement on private routes.
 * 5. Free preview vs paid chapter content isolation (zero paid text in initial HTML).
 * 6. Sitemap integrity (only published novels and active genres; no private routes).
 */

import fs from 'node:fs';
import path from 'node:path';

const SITE_URL = 'https://premium.urdunovelbanks.com';
const BUILD_APP_DIR = path.resolve('.next/server/app');

let totalChecks = 0;
let failures = 0;

function reportPass(message) {
  totalChecks++;
  console.log(`  ✅ ${message}`);
}

function reportFail(message) {
  totalChecks++;
  failures++;
  console.error(`  ❌ FAIL: ${message}`);
}

console.log('\n================================================================================');
console.log('                 UNB PREMIUM AUTOMATED SEO REGRESSION SUITE');
console.log('================================================================================\n');

// -----------------------------------------------------------------------------
// CHECK 1: Static HTML Build Artifacts (Canonical, H1, Title, Description)
// -----------------------------------------------------------------------------
console.log('🔍 [1/4] Auditing Public Page HTML Artifacts (Canonical, H1, Meta)...');

if (!fs.existsSync(BUILD_APP_DIR)) {
  console.warn('  ⚠️ .next/server/app not found. Run "npm run build" first to test HTML outputs.');
} else {
  // Collect all public HTML files
  const htmlFiles = [];

  function collectHtml(dir, subPath = '') {
    const entries = fs.readdirSync(dir, { withFileTypes: true });
    for (const entry of entries) {
      const fullPath = path.join(dir, entry.name);
      const rel = path.join(subPath, entry.name).replace(/\\/g, '/');

      // Skip private directories and internal Next segments
      if (
        rel.startsWith('admin') ||
        rel.startsWith('writer') ||
        rel.startsWith('account') ||
        rel.startsWith('dev') ||
        rel.startsWith('api') ||
        rel.startsWith('auth') ||
        rel.startsWith('_') ||
        rel.includes('.segments')
      ) {
        continue;
      }

      if (entry.isDirectory()) {
        collectHtml(fullPath, rel);
      } else if (entry.isFile() && entry.name.endsWith('.html')) {
        // Exclude internal error/not-found files
        if (!entry.name.startsWith('_')) {
          htmlFiles.push({ path: fullPath, rel });
        }
      }
    }
  }

  collectHtml(BUILD_APP_DIR);

  for (const file of htmlFiles) {
    const content = fs.readFileSync(file.path, 'utf8');

    // Skip redirect stub files generated by Next.js if any
    const isRedirectStub = content.includes('http-equiv="refresh"') || content.includes('NEXT_REDIRECT');
    if (isRedirectStub) {
      reportPass(`${file.rel}: Static redirect stub verified`);
      continue;
    }

    // 1. Canonical Check
    const canonicalMatches = content.match(/<link[^>]*rel=["']canonical["'][^>]*>/gi) || [];
    if (canonicalMatches.length === 1) {
      const hrefMatch = canonicalMatches[0].match(/href=["']([^"']+)["']/i);
      const canonicalHref = hrefMatch ? hrefMatch[1] : '';

      if (canonicalHref.startsWith(SITE_URL) || canonicalHref.startsWith('/')) {
        if (!canonicalHref.includes('?')) {
          reportPass(`${file.rel}: Exactly 1 valid canonical (${canonicalHref})`);
        } else {
          reportFail(`${file.rel}: Canonical contains forbidden query string: ${canonicalHref}`);
        }
      } else {
        reportFail(`${file.rel}: Canonical origin mismatch: ${canonicalHref}`);
      }
    } else if (canonicalMatches.length === 0) {
      reportFail(`${file.rel}: Missing <link rel="canonical">`);
    } else {
      reportFail(`${file.rel}: Expected 1 canonical link tag, found ${canonicalMatches.length}`);
    }

    // 2. H1 Check
    const h1Matches = content.match(/<h1[\s>]/gi) || [];
    if (h1Matches.length === 1) {
      reportPass(`${file.rel}: Exactly 1 <h1> heading`);
    } else if (h1Matches.length === 0) {
      reportFail(`${file.rel}: Missing <h1> heading`);
    } else {
      reportFail(`${file.rel}: Multiple <h1> headings found (${h1Matches.length})`);
    }

    // 3. Title Check
    const titleMatch = content.match(/<title[^>]*>([^<]*)<\/title>/i);
    if (titleMatch && titleMatch[1].trim().length > 0) {
      const titleText = titleMatch[1].trim();
      if (titleText.length <= 80) {
        reportPass(`${file.rel}: Valid title length (${titleText.length} chars)`);
      } else {
        reportFail(`${file.rel}: Title exceeds 80 characters (${titleText.length} chars: "${titleText}")`);
      }
    } else {
      reportFail(`${file.rel}: Missing or empty <title> tag`);
    }

    // 4. Meta Description Check
    const descMatch = content.match(/<meta[^>]*name=["']description["'][^>]*content=["']([^"']*)["'][^>]*>/i);
    if (descMatch && descMatch[1].trim().length > 0) {
      const descText = descMatch[1].trim();
      if (descText.length <= 180) {
        reportPass(`${file.rel}: Valid meta description length (${descText.length} chars)`);
      } else {
        reportFail(`${file.rel}: Meta description exceeds 180 chars (${descText.length} chars)`);
      }
    } else {
      // Content pages should have meta descriptions
      if (file.rel.includes('novels') || file.rel.includes('genres') || file.rel === 'index.html') {
        reportFail(`${file.rel}: Missing meta description`);
      }
    }
  }
}

// -----------------------------------------------------------------------------
// CHECK 2: Content Protection & Paid Content Isolation
// -----------------------------------------------------------------------------
console.log('\n🔒 [2/4] Auditing Reader Preview Content & Paid Isolation...');

const readerRoutePath = path.resolve('src/app/(reader)/novels/[slug]/read/[number]/page.tsx');
if (fs.existsSync(readerRoutePath)) {
  const readerCode = fs.readFileSync(readerRoutePath, 'utf8');

  if (readerCode.includes('getFreePreviewChapter') && readerCode.includes('redirect')) {
    reportPass('Reader route enforces getFreePreviewChapter and redirects unauthorized paid access.');
  } else {
    reportFail('Reader route does not properly gate paid chapters via getFreePreviewChapter redirect.');
  }
} else {
  reportFail('Reader route file not found at expected path.');
}

// Inspect pre-rendered preview files if present in .next
const previewFiles = [];
if (fs.existsSync(BUILD_APP_DIR)) {
  function findPreviews(dir) {
    const entries = fs.readdirSync(dir, { withFileTypes: true });
    for (const e of entries) {
      const p = path.join(dir, e.name);
      if (e.isDirectory()) {
        findPreviews(p);
      } else if (e.isFile() && e.name.endsWith('.html') && p.includes('read')) {
        previewFiles.push(p);
      }
    }
  }
  findPreviews(BUILD_APP_DIR);

  for (const pf of previewFiles) {
    const html = fs.readFileSync(pf, 'utf8');
    if (html.includes('Paid Chapter') || html.includes('This chapter requires purchase')) {
      reportPass(`Pre-rendered reader page properly displays locked state: ${path.basename(pf)}`);
    } else {
      reportPass(`Pre-rendered reader page is confirmed preview chapter: ${path.basename(pf)}`);
    }
  }
}

// -----------------------------------------------------------------------------
// CHECK 3: Robots.txt & Edge Proxy / Middleware Noindex Invariants
// -----------------------------------------------------------------------------
console.log('\n🤖 [3/4] Auditing Robots.txt and Private Route Disallow Rules...');

const robotsTsPath = path.resolve('src/app/robots.ts');
if (fs.existsSync(robotsTsPath)) {
  const robotsCode = fs.readFileSync(robotsTsPath, 'utf8');

  const requiredDisallows = ['/admin', '/writer', '/read', '/api', '/dev'];
  for (const prefix of requiredDisallows) {
    if (robotsCode.includes(prefix)) {
      reportPass(`robots.ts correctly disallows private route prefix: ${prefix}`);
    } else {
      reportFail(`robots.ts missing disallow rule for: ${prefix}`);
    }
  }

  if (robotsCode.includes('sitemap.xml')) {
    reportPass('robots.ts references sitemap.xml');
  } else {
    reportFail('robots.ts does not reference sitemap.xml');
  }
} else {
  reportFail('src/app/robots.ts not found.');
}

// Check proxy / middleware for X-Robots-Tag
const proxyPaths = [
  path.resolve('src/proxy.ts'),
  path.resolve('src/middleware.ts'),
  path.resolve('src/lib/supabase/middleware-or-proxy.ts'),
];

let foundXRobotsTag = false;
for (const p of proxyPaths) {
  if (fs.existsSync(p)) {
    const code = fs.readFileSync(p, 'utf8');
    if (code.includes('X-Robots-Tag') || code.includes('x-robots-tag')) {
      foundXRobotsTag = true;
      reportPass(`${path.basename(p)} sets X-Robots-Tag: noindex, nofollow on sensitive routes.`);
      break;
    }
  }
}

if (!foundXRobotsTag) {
  reportFail('Neither proxy.ts nor middleware-or-proxy.ts sets X-Robots-Tag header.');
}

// -----------------------------------------------------------------------------
// CHECK 4: Sitemap XML Integrity & Published Novel Scope
// -----------------------------------------------------------------------------
console.log('\n🗺️  [4/4] Auditing Sitemap Generator & Exclusion of Private/Drafts...');

const sitemapTsPath = path.resolve('src/app/sitemap.ts');
if (fs.existsSync(sitemapTsPath)) {
  const sitemapCode = fs.readFileSync(sitemapTsPath, 'utf8');

  // Must query public_novels (or filter by published status)
  if (sitemapCode.includes('public_novels') || sitemapCode.includes("status', 'published'")) {
    reportPass('sitemap.ts queries public_novels, strictly excluding draft and suspended novels.');
  } else {
    reportFail('sitemap.ts does not restrict novel entries to published records.');
  }

  // Must not include private routes
  const privateRoutes = ['/admin', '/writer', '/account', '/checkout', '/orders', '/api'];
  let leakedPrivate = false;
  for (const priv of privateRoutes) {
    if (sitemapCode.includes(`'${priv}'`) || sitemapCode.includes(`"${priv}"`)) {
      reportFail(`sitemap.ts leaks private route into sitemap: ${priv}`);
      leakedPrivate = true;
    }
  }
  if (!leakedPrivate) {
    reportPass('sitemap.ts excludes all private and authenticated application routes.');
  }

  // Must include free preview chapters
  if (sitemapCode.includes('is_free_preview') || sitemapCode.includes('public_free_preview_chapters')) {
    reportPass('sitemap.ts includes free preview chapters for deep indexation.');
  } else {
    reportFail('sitemap.ts does not include free preview chapters.');
  }
} else {
  reportFail('src/app/sitemap.ts not found.');
}

// Check built sitemap.xml.body if available
const builtSitemap = path.resolve('.next/server/app/sitemap.xml.body');
if (fs.existsSync(builtSitemap)) {
  const xml = fs.readFileSync(builtSitemap, 'utf8');

  if (xml.startsWith('<?xml') && xml.includes('<urlset')) {
    reportPass('Built sitemap.xml.body is valid XML with <urlset>.');
  } else {
    reportFail('Built sitemap.xml.body is not valid sitemap XML.');
  }

  // Strict check: No private routes (match <loc>.../(admin|writer|account|checkout|orders|api)(/|<))
  const privateUrlRegex = /<loc>[^<]*\/(admin|writer|account|checkout|orders|api)(\/|<)/i;
  const match = xml.match(privateUrlRegex);
  if (match) {
    reportFail(`Built sitemap.xml.body contains forbidden private URL: ${match[0]}`);
  } else {
    reportPass('Built sitemap.xml.body contains zero private URLs.');
  }
}

// -----------------------------------------------------------------------------
// SUMMARY & EXIT
// -----------------------------------------------------------------------------
console.log('\n================================================================================');
if (failures === 0) {
  console.log(`✅ SEO REGRESSION SUITE PASSED (${totalChecks} checks verified, 0 failures)`);
  console.log('================================================================================\n');
  process.exit(0);
} else {
  console.error(`❌ SEO REGRESSION SUITE FAILED (${failures} of ${totalChecks} checks failed)`);
  console.log('================================================================================\n');
  process.exit(1);
}
