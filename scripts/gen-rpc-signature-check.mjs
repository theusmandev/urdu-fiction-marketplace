#!/usr/bin/env node
// scripts/gen-rpc-signature-check.mjs
//
// Extracts every .rpc('function_name', { ...args }) call in src/ via TypeScript AST
// and generates supabase/tests/15_rpc_signature_check.sql.

import { readFileSync, readdirSync, statSync, writeFileSync } from 'fs';
import { join, relative, extname } from 'path';
import { fileURLToPath } from 'url';
import ts from 'typescript';

const REPO_ROOT = join(fileURLToPath(new URL('.', import.meta.url)), '..');
const SRC_DIR = join(REPO_ROOT, 'src');
const OUTPUT_SQL_PATH = join(REPO_ROOT, 'supabase', 'tests', '15_rpc_signature_check.sql');

function getSourceFiles(dir) {
  const files = [];
  const entries = readdirSync(dir);
  for (const entry of entries) {
    const fullPath = join(dir, entry);
    const stat = statSync(fullPath);
    if (stat.isDirectory()) {
      files.push(...getSourceFiles(fullPath));
    } else if (['.ts', '.tsx'].includes(extname(fullPath))) {
      files.push(fullPath);
    }
  }
  return files;
}

export function extractRpcCalls() {
  const files = getSourceFiles(SRC_DIR);
  const rpcCalls = [];

  for (const file of files) {
    const code = readFileSync(file, 'utf8');
    const sourceFile = ts.createSourceFile(file, code, ts.ScriptTarget.Latest, true);

    function visit(node) {
      if (ts.isCallExpression(node)) {
        const expr = node.expression;
        if (ts.isPropertyAccessExpression(expr) && expr.name.text === 'rpc') {
          const { line } = sourceFile.getLineAndCharacterOfPosition(node.getStart());
          const lineNumber = line + 1;
          const args = node.arguments;

          let funcName = null;
          if (args.length > 0) {
            const firstArg = args[0];
            if (ts.isStringLiteral(firstArg) || ts.isNoSubstitutionTemplateLiteral(firstArg)) {
              funcName = firstArg.text;
            } else {
              funcName = firstArg.getText(sourceFile);
            }
          }

          let sentArgs = [];
          let isDynamic = false;
          let dynamicReason = null;

          if (args.length > 1) {
            const secondArg = args[1];
            if (ts.isObjectLiteralExpression(secondArg)) {
              for (const prop of secondArg.properties) {
                if (ts.isPropertyAssignment(prop) || ts.isShorthandPropertyAssignment(prop)) {
                  const keyName = prop.name.getText(sourceFile).replace(/^['"]|['"]$/g, '');
                  sentArgs.push(keyName);
                } else if (ts.isSpreadAssignment(prop)) {
                  isDynamic = true;
                  dynamicReason = `Spread element in arguments: ${prop.expression.getText(sourceFile)}`;
                } else {
                  isDynamic = true;
                  dynamicReason = `Dynamic property assignment: ${prop.getText(sourceFile)}`;
                }
              }
            } else if (ts.isIdentifier(secondArg) || ts.isCallExpression(secondArg) || ts.isPropertyAccessExpression(secondArg)) {
              isDynamic = true;
              dynamicReason = `Arguments passed as variable or expression: ${secondArg.getText(sourceFile)}`;
            } else {
              isDynamic = true;
              dynamicReason = `Non-object argument passed: ${secondArg.getText(sourceFile)}`;
            }
          }

          rpcCalls.push({
            funcName,
            filePath: relative(REPO_ROOT, file).replace(/\\/g, '/'),
            line: lineNumber,
            sentArgs,
            isDynamic,
            dynamicReason,
          });
        }
      }
      ts.forEachChild(node, visit);
    }

    visit(sourceFile);
  }

  return rpcCalls;
}

export function generateSql(rpcCalls) {
  const insertStatements = rpcCalls.map((call, idx) => {
    const id = idx + 1;
    const func = (call.funcName || 'unknown').replace(/'/g, "''");
    const file = call.filePath.replace(/'/g, "''");
    const line = call.line;
    const argsArr = call.sentArgs.length > 0 
      ? `ARRAY[${call.sentArgs.map(a => `'${a.replace(/'/g, "''")}'`).join(', ')}]::text[]`
      : `ARRAY[]::text[]`;
    const isDyn = call.isDynamic ? 'TRUE' : 'FALSE';
    const dynReason = call.dynamicReason ? `'${call.dynamicReason.replace(/'/g, "''")}'` : 'NULL';

    return `    (${id}, '${func}', '${file}', ${line}, ${argsArr}, ${isDyn}, ${dynReason})`;
  }).join(',\n');

  return `-- ==============================================================================
-- UNB PREMIUM — AUTOMATED TEST SUITE: MECHANICAL RPC SIGNATURE CHECK (15)
-- ==============================================================================
-- File: supabase/tests/15_rpc_signature_check.sql
-- Generated by: scripts/gen-rpc-signature-check.mjs
-- Description:
--   Mechanically validates every .rpc('name', args) call site extracted from src/
--   against PostgreSQL system catalog (pg_proc, pg_namespace).
--
-- Invariants Checked:
--   1. Target function exists in schema 'public'.
--   2. All non-default input parameters are provided by caller.
--   3. No unknown/unexpected parameter keys are sent.
--   4. Flag dynamic argument patterns for explicit manual review.
--   5. Transaction ends in ROLLBACK with zero database mutations.
-- ==============================================================================

BEGIN;

CREATE TEMP TABLE rpc_call_sites (
    call_id integer PRIMARY KEY,
    func_name text NOT NULL,
    file_path text NOT NULL,
    line_num integer NOT NULL,
    sent_args text[] NOT NULL,
    is_dynamic boolean NOT NULL DEFAULT false,
    dynamic_reason text
);

CREATE TEMP TABLE rpc_signature_results (
    call_id integer,
    func_name text,
    call_site text,
    status text,
    missing_parameters text,
    unknown_keys text,
    existing_signatures text,
    details text
);

INSERT INTO rpc_call_sites (call_id, func_name, file_path, line_num, sent_args, is_dynamic, dynamic_reason)
VALUES
${insertStatements};

DO $$
DECLARE
    r record;
    v_proc_rec record;
    v_proc_count integer;
    v_matched boolean;
    v_all_signatures text;
    v_in_names text[];
    v_req_names text[];
    v_num_in integer;
    v_num_defaults integer;
    v_num_req integer;
    v_i integer;
    v_mode text;
    v_missing_req text[];
    v_unknown_keys text[];
    v_best_missing text;
    v_best_unknown text;
BEGIN
    FOR r IN SELECT * FROM rpc_call_sites ORDER BY call_id LOOP
        SELECT count(*) INTO v_proc_count
        FROM pg_proc p
        JOIN pg_namespace n ON n.oid = p.pronamespace
        WHERE n.nspname = 'public' AND p.proname = r.func_name;

        IF v_proc_count = 0 THEN
            INSERT INTO rpc_signature_results VALUES (
                r.call_id,
                r.func_name,
                r.file_path || ':' || r.line_num,
                'FAIL',
                'N/A',
                coalesce(array_to_string(r.sent_args, ', '), 'none'),
                'NONE',
                'Function public.' || r.func_name || ' does NOT exist in database schema'
            );
            CONTINUE;
        END IF;

        -- Collect all overload signatures
        SELECT string_agg(p.proname || '(' || pg_get_function_arguments(p.oid) || ')', ' | ')
        INTO v_all_signatures
        FROM pg_proc p
        JOIN pg_namespace n ON n.oid = p.pronamespace
        WHERE n.nspname = 'public' AND p.proname = r.func_name;

        v_matched := false;
        v_best_missing := '';
        v_best_unknown := '';

        FOR v_proc_rec IN
            SELECT p.oid, p.proname, p.proargnames, p.proargmodes, p.pronargdefaults, p.pronargs,
                   pg_get_function_arguments(p.oid) as sig
            FROM pg_proc p
            JOIN pg_namespace n ON n.oid = p.pronamespace
            WHERE n.nspname = 'public' AND p.proname = r.func_name
        LOOP
            -- Build input parameter names
            v_in_names := ARRAY[]::text[];
            IF v_proc_rec.proargnames IS NOT NULL THEN
                FOR v_i IN 1 .. cardinality(v_proc_rec.proargnames) LOOP
                    v_mode := 'i';
                    IF v_proc_rec.proargmodes IS NOT NULL THEN
                        v_mode := v_proc_rec.proargmodes[v_i];
                    END IF;
                    IF v_mode IN ('i', 'b', 'v') THEN
                        v_in_names := array_append(v_in_names, v_proc_rec.proargnames[v_i]);
                    END IF;
                END LOOP;
            END IF;

            v_num_in := coalesce(cardinality(v_in_names), 0);
            v_num_defaults := coalesce(v_proc_rec.pronargdefaults, 0);
            v_num_req := v_num_in - v_num_defaults;

            v_req_names := ARRAY[]::text[];
            IF v_num_req > 0 AND v_num_in > 0 THEN
                FOR v_i IN 1 .. v_num_req LOOP
                    v_req_names := array_append(v_req_names, v_in_names[v_i]);
                END LOOP;
            END IF;

            -- Check missing required
            v_missing_req := ARRAY[]::text[];
            IF cardinality(v_req_names) > 0 THEN
                SELECT coalesce(array_agg(p), ARRAY[]::text[])
                INTO v_missing_req
                FROM unnest(v_req_names) p
                WHERE p != ALL(r.sent_args);
            END IF;

            -- Check unknown keys
            v_unknown_keys := ARRAY[]::text[];
            IF cardinality(r.sent_args) > 0 THEN
                SELECT coalesce(array_agg(a), ARRAY[]::text[])
                INTO v_unknown_keys
                FROM unnest(r.sent_args) a
                WHERE a != ALL(v_in_names);
            END IF;

            IF cardinality(v_missing_req) = 0 AND cardinality(v_unknown_keys) = 0 THEN
                v_matched := true;
                EXIT;
            ELSE
                v_best_missing := coalesce(array_to_string(v_missing_req, ', '), '');
                v_best_unknown := coalesce(array_to_string(v_unknown_keys, ', '), '');
            END IF;
        END LOOP;

        IF r.is_dynamic THEN
            INSERT INTO rpc_signature_results VALUES (
                r.call_id,
                r.func_name,
                r.file_path || ':' || r.line_num,
                'DYNAMIC_CHECK',
                v_best_missing,
                v_best_unknown,
                v_all_signatures,
                'Dynamic arguments: ' || coalesce(r.dynamic_reason, 'verify manually')
            );
        ELSIF v_matched THEN
            INSERT INTO rpc_signature_results VALUES (
                r.call_id,
                r.func_name,
                r.file_path || ':' || r.line_num,
                'PASS',
                'none',
                'none',
                v_all_signatures,
                'Signature matches PostgreSQL catalog definition'
            );
        ELSE
            INSERT INTO rpc_signature_results VALUES (
                r.call_id,
                r.func_name,
                r.file_path || ':' || r.line_num,
                'FAIL',
                nullif(v_best_missing, ''),
                nullif(v_best_unknown, ''),
                v_all_signatures,
                'Sent keys do not match any overload signature'
            );
        END IF;
    END LOOP;
END $$;

-- ------------------------------------------------------------------------------
-- DETAILED PASS / FAIL TABLE
-- ------------------------------------------------------------------------------
SELECT 
    call_id,
    func_name,
    call_site,
    status,
    coalesce(missing_parameters, '-') AS missing_params,
    coalesce(unknown_keys, '-') AS unknown_keys,
    existing_signatures
FROM rpc_signature_results
ORDER BY call_id;

-- ------------------------------------------------------------------------------
-- SUMMARY REPORT
-- ------------------------------------------------------------------------------
SELECT 
    count(*) AS total_calls,
    count(*) FILTER (WHERE status = 'PASS') AS passed,
    count(*) FILTER (WHERE status = 'FAIL') AS failed,
    count(*) FILTER (WHERE status = 'DYNAMIC_CHECK') AS dynamic_to_verify_manually
FROM rpc_signature_results;

DO $$
DECLARE
    v_fail_count integer;
BEGIN
    SELECT count(*) INTO v_fail_count FROM rpc_signature_results WHERE status = 'FAIL';
    IF v_fail_count > 0 THEN
        RAISE EXCEPTION 'TEST 15 FAILED: % RPC signature mismatch(es) detected.', v_fail_count;
    END IF;
END $$;

ROLLBACK;
`;
}

// Main execution
const calls = extractRpcCalls();
const sql = generateSql(calls);
writeFileSync(OUTPUT_SQL_PATH, sql, 'utf8');

console.log(`[gen-rpc-signature-check] Scanned src/ and extracted ${calls.length} .rpc(...) call sites.`);
console.log(`[gen-rpc-signature-check] Generated: supabase/tests/15_rpc_signature_check.sql`);
